"""
db/migrate.py: the schema-migration ledger and runner (CLOSE_OUT_CHECKLIST P1-02; PROJECT_SPEC §1.1/§3).

Before this tool, "what is applied where" was guessed from `to_regclass` on a table by table basis. Now every
`db/migrations/*.sql` file is recorded in `schema_migrations` when it is applied, so the state of a database is
one query:

    python3 -m db.migrate status --dsn "host=localhost dbname=madden_test user=postgres password=postgres"

`db/init_db.sql` mirrors every migration, so a database built from it is at the head of the list. Its ledger
block (generated by `sync-init-db`) marks every migration applied: `status` reports nothing pending and `apply`
is a no-op on a fresh build.

Migrations are applied in filename order, each in its own transaction together with its ledger row. The files
in `db/migrations/*.py` are data-fix modules, not schema migrations, and are run by hand as before, so they are
not in the ledger.

Commands (all take --dsn; DATABASE_URL is the default):

    status                 what is applied, pending, or drifted (checksum changed since it was recorded)
    apply [--dry-run]      apply pending files in order, recording each
    baseline --confirm-head  record every file as applied on a database already at the head of the list
    diff --a DSN --b DSN   compare two databases' schemas object by object
    sync-init-db           regenerate the ledger block at the end of db/init_db.sql

Refuses the frozen `madden_2036` archive. Exit 0 ok, 1 a schema/ledger problem, 2 bad input.
"""
import argparse
import hashlib
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MIGRATIONS_DIR = ROOT / "db" / "migrations"
INIT_DB = ROOT / "db" / "init_db.sql"
LEDGER = "schema_migrations"
DEFAULT_DSN = "host=localhost dbname=madden user=postgres password=postgres"
REFUSED_DBS = {"madden_2036", "postgres", "template0", "template1"}

BLOCK_START = "-- >>> MIGRATION LEDGER"
BLOCK_END = "-- <<< MIGRATION LEDGER"

LEDGER_DDL = """CREATE TABLE IF NOT EXISTS schema_migrations (
    version    TEXT PRIMARY KEY,
    filename   TEXT NOT NULL UNIQUE,
    checksum   TEXT NOT NULL,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    source     TEXT NOT NULL DEFAULT 'applied'
);"""


class MigrationError(Exception):
    pass


# --- discovery --------------------------------------------------------------------------------------------

def migration_files():
    """Every schema migration, in apply order."""
    return sorted(MIGRATIONS_DIR.glob("*.sql"))


def version_of(path):
    return Path(path).stem


def checksum(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def migrations():
    return [{"version": version_of(p), "filename": Path(p).name, "path": Path(p), "checksum": checksum(p)}
            for p in migration_files()]


# --- DSN --------------------------------------------------------------------------------------------------

def dbname_of(dsn):
    m = re.search(r"(?:^|\s)dbname\s*=\s*([^\s'\"]+)", dsn or "")
    if m:
        return m.group(1)
    m = re.search(r"postgres(?:ql)?://[^/]+/([^\s?]+)", dsn or "")
    return m.group(1) if m else ""


def check_dsn(dsn):
    name = dbname_of(dsn)
    if name in REFUSED_DBS:
        raise MigrationError(f"refusing to run migrations against {name!r}")


# --- ledger -----------------------------------------------------------------------------------------------

def ensure_ledger(conn):
    conn.execute(LEDGER_DDL)


def applied_rows(conn):
    """version -> {filename, checksum, applied_at, source}; empty when the ledger does not exist."""
    if conn.execute("SELECT to_regclass(%s)", (f"public.{LEDGER}",)).fetchone()[0] is None:
        return {}
    rows = conn.execute(f"SELECT version, filename, checksum, applied_at, source FROM {LEDGER}").fetchall()
    return {r[0]: {"filename": r[1], "checksum": r[2], "applied_at": r[3], "source": r[4]} for r in rows}


def status_of(conn):
    """One entry per migration: state is applied / pending / drift / unknown (ledger row, no file)."""
    known = applied_rows(conn)
    out = []
    for m in migrations():
        row = known.pop(m["version"], None)
        if row is None:
            state = "pending"
        elif row["checksum"] != m["checksum"]:
            state = "drift"
        else:
            state = "applied"
        out.append({**m, "state": state, "source": (row or {}).get("source")})
    for version, row in known.items():
        out.append({"version": version, "filename": row["filename"], "checksum": row["checksum"],
                    "state": "unknown", "source": row["source"]})
    return out


# --- applying ---------------------------------------------------------------------------------------------

def _strip_outer_transaction(sql):
    """Drop the file's own leading BEGIN; and trailing COMMIT; so the caller owns the transaction."""
    body = re.sub(r"(?im)^[ \t]*BEGIN[ \t]*;[ \t]*\n", "", sql, count=1)
    body = re.sub(r"(?is)\s*COMMIT[ \t]*;[ \t]*$", "", body)
    return body


def _apply_sql(path, m):
    """The migration body plus its ledger row, one transaction, run with the simple query protocol."""
    body = _strip_outer_transaction(Path(path).read_text())
    values = ", ".join(_sql_literal(v) for v in (m["version"], m["filename"], m["checksum"], "applied"))
    return (f"BEGIN;\n{body}\n;\n"
            f"INSERT INTO {LEDGER} (version, filename, checksum, source) VALUES ({values}) "
            f"ON CONFLICT (version) DO UPDATE SET checksum = EXCLUDED.checksum, source = EXCLUDED.source;\nCOMMIT;")


def apply_migration(conn, m):
    conn.execute(_apply_sql(m["path"], m))


def apply(conn, dry_run=False, only=None):
    """Apply pending migrations in order. Returns the versions applied (or that would be, with dry_run)."""
    ensure_ledger(conn)
    known = applied_rows(conn)
    todo = []
    for m in migrations():
        row = known.get(m["version"])
        if only and m["version"] != only and m["filename"] != only:
            continue
        if row is None:
            todo.append(m)
        elif row["checksum"] != m["checksum"]:
            raise MigrationError(f"{m['filename']} was recorded with a different checksum; its file changed "
                                 f"after it was applied")
    if dry_run:
        return [m["version"] for m in todo]
    for m in todo:
        apply_migration(conn, m)
    return [m["version"] for m in todo]


def baseline(conn):
    """Record every migration as applied. Only for a database already at the head of db/migrations/."""
    ensure_ledger(conn)
    known = applied_rows(conn)
    rows = [(m["version"], m["filename"], m["checksum"], "baseline") for m in migrations()
            if m["version"] not in known]
    for version, filename, sum_, source in rows:
        conn.execute(f"INSERT INTO {LEDGER} (version, filename, checksum, source) VALUES (%s, %s, %s, %s) "
                     f"ON CONFLICT (version) DO NOTHING", (version, filename, sum_, source))
    return [r[0] for r in rows]


# --- init_db.sql ledger block -----------------------------------------------------------------------------

def _sql_literal(value):
    return "'" + str(value).replace("'", "''") + "'"


def ledger_block():
    """The generated block: the ledger table plus one row per migration (a fresh build is at the head)."""
    lines = [
        BLOCK_START,
        "-- Generated by `python3 -m db.migrate sync-init-db`; do not edit by hand.",
        "-- db/init_db.sql mirrors every file under db/migrations/, so a database built from this file is at",
        "-- the head of the list: `python3 -m db.migrate status` reports nothing pending and apply is a no-op.",
        BLOCK_END,
        "",
        LEDGER_DDL,
        "",
        f"INSERT INTO {LEDGER} (version, filename, checksum, source) VALUES",
    ]
    rows = migrations()
    for i, m in enumerate(rows):
        sep = "," if i < len(rows) - 1 else ""
        lines.append(f"    ({_sql_literal(m['version'])}, {_sql_literal(m['filename'])}, "
                     f"{_sql_literal(m['checksum'])}, 'init_db.sql'){sep}")
    lines.append("ON CONFLICT (version) DO NOTHING;")
    return "\n".join(lines)


def sync_init_db(path=INIT_DB):
    """Replace (or append) the ledger block in db/init_db.sql. Returns True when the file changed."""
    text = Path(path).read_text()
    block = ledger_block()
    pattern = re.compile(rf"{re.escape(BLOCK_START)}.*?{re.escape(BLOCK_END)}\n\n.*?ON CONFLICT \(version\) DO NOTHING;\n",
                         re.DOTALL)
    if pattern.search(text):
        new = pattern.sub(block + "\n", text, count=1)
    else:
        new = text.rstrip("\n") + "\n\n" + "-- ---------------------------------------------------------------------------\n" \
              "-- Migration ledger (schema_migrations; db/migrate.py)\n" \
              "-- ---------------------------------------------------------------------------\n\n" + block + "\n"
    if new != text:
        Path(path).write_text(new)
        return True
    return False


# --- schema comparison ------------------------------------------------------------------------------------

SCHEMA_QUERIES = {
    "tables": """
        SELECT c.relname || '.' || a.attname AS key,
               c.relname || ' ' || a.attname || ' ' || pg_catalog.format_type(a.atttypid, a.atttypmod)
               || ' notnull=' || a.attnotnull || ' default=' || coalesce(pg_get_expr(d.adbin, d.adrelid), '-')
               || ' generated=' || a.attgenerated || ' identity=' || a.attidentity AS value
        FROM pg_attribute a
        JOIN pg_class c ON c.oid = a.attrelid
        JOIN pg_namespace n ON n.oid = c.relnamespace
        LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
        WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p') AND a.attnum > 0 AND NOT a.attisdropped
        ORDER BY c.relname, a.attnum""",
    "views": """
        SELECT viewname AS key, definition AS value FROM pg_views
        WHERE schemaname = 'public' ORDER BY viewname""",
    "indexes": """
        SELECT tablename || '.' || indexname AS key, indexdef AS value FROM pg_indexes
        WHERE schemaname = 'public' ORDER BY tablename, indexname""",
    "constraints": """
        SELECT conrelid::regclass::text || '.' || conname AS key,
               contype || ' ' || pg_get_constraintdef(oid) AS value
        FROM pg_constraint WHERE connamespace = 'public'::regnamespace ORDER BY 1""",
    "sequences": """
        SELECT sequence_name AS key,
               data_type || ' start=' || start_value || ' inc=' || increment
               || ' min=' || minimum_value || ' max=' || maximum_value AS value
        FROM information_schema.sequences WHERE sequence_schema = 'public' ORDER BY sequence_name""",
    "functions": """
        SELECT p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')' AS key,
               pg_get_functiondef(p.oid) AS value
        FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
        WHERE n.nspname = 'public' ORDER BY 1""",
    "triggers": """
        SELECT tgrelid::regclass::text || '.' || tgname AS key, pg_get_triggerdef(oid) AS value
        FROM pg_trigger WHERE NOT tgisinternal ORDER BY 1""",
}


def _canon_ws(text):
    return re.sub(r"\s+", " ", text).strip()


def _canon(text):
    """Fold the two server renderings of the same expression (cast form and array-literal form)."""
    t = re.sub(r"::(?:character varying|varchar|text)\[\]", "", text, flags=re.I)
    t = re.sub(r"::(?:character varying|varchar|text|smallint|integer|bigint|numeric(?:\(\d+,\d+\))?|"
               r"boolean|jsonb|timestamp(?: with(?:out)? time zone)?|date)\b", "", t, flags=re.I)
    t = re.sub(r"\(\s*('[^']*')\s*\)", r"\1", t)
    t = re.sub(r"\(\s*\((ARRAY\[.*?\])\)\s*\)", r"(\1)", t)
    return _canon_ws(t)


CANONICAL_KINDS = {"constraints": _canon, "indexes": _canon, "functions": _canon_ws, "views": _canon_ws}


def schema_snapshot(conn):
    """{kind: {key: value}} for every schema object migrate.py compares."""
    return {kind: {k: (CANONICAL_KINDS[kind](v) if kind in CANONICAL_KINDS else v)
                   for k, v in conn.execute(sql).fetchall()}
            for kind, sql in SCHEMA_QUERIES.items()}


def compare_schemas(a, b, labels=("a", "b")):
    """Human-readable differences between two snapshots ([] when identical)."""
    out = []
    for kind in SCHEMA_QUERIES:
        left, right = a.get(kind, {}), b.get(kind, {})
        for key in sorted(left.keys() - right.keys()):
            out.append(f"{kind}: {key} only in {labels[0]}")
        for key in sorted(right.keys() - left.keys()):
            out.append(f"{kind}: {key} only in {labels[1]}")
        for key in sorted(left.keys() & right.keys()):
            if left[key] != right[key]:
                out.append(f"{kind}: {key} differs\n    {labels[0]}: {left[key]}\n    {labels[1]}: {right[key]}")
    return out


# --- CLI --------------------------------------------------------------------------------------------------

def _connect(dsn):
    import psycopg
    return psycopg.connect(dsn, autocommit=True)


def _print_status(dsn, entries):
    applied = sum(1 for e in entries if e["state"] == "applied")
    print(f"{dbname_of(dsn) or dsn}: {applied} applied, "
          f"{sum(1 for e in entries if e['state'] == 'pending')} pending, "
          f"{sum(1 for e in entries if e['state'] == 'drift')} drifted, "
          f"{sum(1 for e in entries if e['state'] == 'unknown')} in ledger only")
    for e in entries:
        mark = {"applied": "ok  ", "pending": "PEND", "drift": "DRIFT", "unknown": "??  "}[e["state"]]
        source = f" ({e['source']})" if e.get("source") else ""
        print(f"  {mark} {e['filename']}{source}")


def main(argv=None):
    ap = argparse.ArgumentParser(description="Project Mu schema migration ledger (db/migrate.py)")
    sub = ap.add_subparsers(dest="cmd", required=True)

    for name, help_ in (("status", "what is applied, pending or drifted"),
                        ("apply", "apply pending migrations"),
                        ("baseline", "record every migration as applied on a database already at head")):
        p = sub.add_parser(name, help=help_)
        p.add_argument("--dsn", default=os.environ.get("DATABASE_URL") or DEFAULT_DSN)
        if name == "apply":
            p.add_argument("--dry-run", action="store_true")
            p.add_argument("--file", help="apply just this version or filename")
        if name == "baseline":
            p.add_argument("--confirm-head", action="store_true",
                           help="the database is known to be at the head of db/migrations/")
    d = sub.add_parser("diff", help="compare two databases' schemas")
    d.add_argument("--a", required=True)
    d.add_argument("--b", required=True)
    s = sub.add_parser("sync-init-db", help="regenerate the ledger block in db/init_db.sql")

    args = ap.parse_args(argv)

    if args.cmd == "sync-init-db":
        changed = sync_init_db()
        print(f"db/init_db.sql {'updated' if changed else 'already current'} ({len(migrations())} migrations)")
        return 0

    if args.cmd == "diff":
        check_dsn(args.a)
        check_dsn(args.b)
        with _connect(args.a) as a, _connect(args.b) as b:
            diffs = compare_schemas(schema_snapshot(a), schema_snapshot(b), (dbname_of(args.a), dbname_of(args.b)))
        if not diffs:
            print("Schemas are identical.")
            return 0
        print("\n".join(diffs))
        return 1

    check_dsn(args.dsn)
    try:
        with _connect(args.dsn) as conn:
            if args.cmd == "status":
                _print_status(args.dsn, status_of(conn))
                return 0
            if args.cmd == "apply":
                done = apply(conn, dry_run=args.dry_run, only=args.file)
                verb = "would apply" if args.dry_run else "applied"
                print(f"{verb} {len(done)} migration(s)" + (":\n  " + "\n  ".join(done) if done else " (no-op)"))
                return 0
            if args.cmd == "baseline":
                if not args.confirm_head:
                    print("baseline records every migration as applied; pass --confirm-head after verifying the "
                          "database is at the head of db/migrations/ (python3 -m db.migrate diff against a fresh "
                          "db/init_db.sql build)", file=sys.stderr)
                    return 2
                done = baseline(conn)
                print(f"baselined {len(done)} migration(s)")
                return 0
    except MigrationError as err:
        print(str(err), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
